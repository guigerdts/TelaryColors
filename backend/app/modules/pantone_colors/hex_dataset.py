def lookup_hex_code(code: str) -> str | None:
    """Raw lookup — strip whitespace, return hex or ``None``."""
    return HEX_BY_CODE.get(code.strip())


def suggest_hex(code: str, gamut: str) -> str | None:
    """Gamut-gated lookup: returns a hex value **only** when *gamut*
    normalises to ``"C"`` (accepts ``"C"`` / ``"c"``).  Otherwise ``None``.

    The *code* is normalised before lookup: leading/trailing whitespace is
    stripped and an optional trailing ``"C"`` / ``" c"`` suffix is removed
    (e.g. ``"211C"``, ``"211c"``, ``"211 C"``, ``" 211 "`` all resolve to
    the raw numeric code ``"211"``).
    """
    if gamut.strip().upper() != "C":
        return None

    normalised = code.strip()
    # Strip an optional trailing "C" / "c" suffix (with or without a space).
    if normalised and normalised[-1].upper() == "C":
        normalised = normalised[:-1].rstrip()

    return HEX_BY_CODE.get(normalised)
